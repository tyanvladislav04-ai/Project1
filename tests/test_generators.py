@pytest.mark.parametrize(
    "start, end, expected_error_message",
    [
        (0, 5, "Начальное значение должно быть от 1 до 9999999999999999"),
        (-1, 5, "Начальное значение должно быть от 1 до 9999999999999999"),
        (1, 10000000000000000, "Конечное значение должно быть от 1 до 9999999999999999"),
        (5, 3, "Начальное значение должно быть меньше конечного"),
    ],
)
def test_card_number_generator_value_error(start, end, expected_error_message):
    with pytest.raises(ValueError, match=expected_error_message):
        list(card_number_generator(start, end))
